"""Reproduce every table and figure in docs/results.md.

    python run_all.py              # SciPy/HiGHS (PuLP cross-check runs if PuLP 2.7-3.x is installed)
    python run_all.py --budget 750000
    python run_all.py --draws 50   # quicker robustness section
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

from check_requirements import check_requirements

# Before the third-party imports below, so a missing package gives a clear message.
check_requirements(Path(__file__).resolve().parent / "requirements.txt")

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Patch  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from optimizer import (brute_force_max_reduction, build_model, effect_uncertainty,  # noqa: E402
                       feasible_subsets, greedy_portfolio, load_instance, lp_relaxation,
                       optimal_portfolio, pulp_unavailable, release_ales, solve_pulp,
                       solve_scipy, summarize)
from optimizer.data import CSF_FUNCTIONS  # noqa: E402

ROOT = Path(__file__).resolve().parent
FIG = ROOT / "docs" / "figures"


def usd(x: float) -> str:
    x = int(round(x))  # so a rounding residue prints as $0, not -$0
    return f"-${-x:,}" if x < 0 else f"${x:,}"


def md_table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    rule = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, rule, *rows])


def main(budget: float | None = None, draws: int = 200) -> dict:
    ales, ale_note = release_ales()
    if ales is None:
        print(f"Using data/scenarios.csv: {ale_note}")
        ale_note = "copy in data/scenarios.csv (release asset unavailable)"

    def load(**overrides):
        return load_instance(ales=ales, ale_source=ale_note, **overrides)

    inst = load()
    budget = float(budget or inst.policy["budget"])
    ctl = inst.controls
    FIG.mkdir(parents=True, exist_ok=True)
    out = []

    # ---- 1. Inputs ------------------------------------------------------------------
    out.append("# Results\n\nGenerated by `python run_all.py`. All inputs are **illustrative** "
               "(see `data/README.md`); scenario ALEs are the mean simulated annual losses from the "
               "companion [cyber-risk-monte-carlo](https://github.com/casildata/cyber-risk-monte-carlo) "
               f"project, read from the {inst.ale_source}.\n")
    scen = inst.scenarios.assign(ale=inst.scenarios["ale"].map(usd)).reset_index()
    out.append("## 1. Inputs\n\n**Risk scenarios** (total ALE " + usd(inst.total_ale) + "):\n\n"
               + md_table(scen.rename(columns={"scenario_id": "id", "ale": "ALE"})))
    cat = ctl.reset_index()[["control_id", "name", "csf_function", "cis_safeguard", "annual_cost",
                             "analyst_hours", "platform", "exclusive_group", "requires"]].copy()
    cat["annual_cost"] = cat["annual_cost"].map(usd)
    out.append("\n**Control catalogue:**\n\n" + md_table(cat))

    # ---- 2. Recommended portfolio -----------------------------------------------------
    model = build_model(inst, budget=budget)
    t0 = time.perf_counter()
    sol = optimal_portfolio(inst, budget)
    solve_ms = 1000 * (time.perf_counter() - t0)
    rec = summarize(inst, sol)
    t0 = time.perf_counter()
    bf_value, _ = brute_force_max_reduction(inst, budget)
    bf_s = time.perf_counter() - t0
    assert abs(bf_value - rec["reduction"]) < 1.0, "MILP and exhaustive search disagree"

    skip_reason = pulp_unavailable()
    if skip_reason is None:
        pulp_sol = solve_pulp(model)
        pulp_note = (f"PuLP/CBC on the same model: {usd(pulp_sol.objective)} "
                     f"({'matches' if abs(pulp_sol.objective - rec['reduction']) < 1 else 'DIFFERS'}).")
    else:
        pulp_note = f"PuLP cross-check skipped ({skip_reason})."

    chosen = ctl.loc[rec["controls"], ["name", "csf_function", "annual_cost", "analyst_hours"]]
    chosen = chosen.reset_index().assign(annual_cost=lambda d: d["annual_cost"].map(usd))
    fees = []
    for p in rec["platforms"]:
        fees.append(f"{inst.policy['platforms'][p]['name']} {usd(inst.policy['platforms'][p]['annual_fee'])}")
    if rec["mssp"]:
        fees.append(f"MSSP {usd(inst.policy['mssp']['annual_fee'])}")
    by_s = rec["by_scenario"].assign(
        share_removed=lambda d: (d["reduction"] / d["ale_before"]).map("{:.0%}".format))
    for c in ("ale_before", "ale_after", "reduction"):
        by_s[c] = by_s[c].map(usd)
    capacity = inst.policy["mssp"]["hours_capacity"] if rec["mssp"] else inst.policy["inhouse_hours"]
    out.append(f"\n## 2. Recommended portfolio at a {usd(budget)} budget\n\n"
               + md_table(chosen) + "\n\n"
               f"- Spend: **{usd(rec['spend'])}**" + (f" (includes {', '.join(fees)})" if fees else "") + "\n"
               f"- Risk reduction: **{usd(rec['reduction'])}** of {usd(inst.total_ale)} "
               f"({rec['reduction'] / inst.total_ale:.0%}); residual ALE {usd(rec['residual_ale'])}\n"
               f"- Net benefit {usd(rec['net_benefit'])} · ROSI {rec['rosi']:+.0%}\n"
               f"- Analyst hours {rec['analyst_hours']:,.0f} of {capacity:,} "
               f"({'MSSP' if rec['mssp'] else 'in-house team'})\n\n"
               + md_table(by_s.reset_index(drop=True)) + "\n\n"
               f"**Verification.** Exhaustive enumeration of all {2 ** len(ctl):,} control subsets "
               f"gives the same optimum, {usd(bf_value)}. {pulp_note}\n")

    # ---- 3. Budget sweep ---------------------------------------------------------------
    min_spend = solve_scipy(build_model(inst, "min_cost", target_share=0.0))
    budgets = np.arange(250_000, 1_200_001, 25_000)
    sweep, selection = [], {}
    for b in budgets:
        s = optimal_portfolio(inst, float(b))
        if not s.optimal:
            sweep.append({"budget": b, "reduction": np.nan, "spend": np.nan})
            continue
        r = summarize(inst, s)
        sweep.append({"budget": b, "reduction": r["reduction"], "spend": r["spend"],
                      "mssp": r["mssp"], "n_controls": len(r["controls"])})
        selection[b] = r["controls"]
    sweep = pd.DataFrame(sweep)
    sweep["net_benefit"] = sweep["reduction"] - sweep["spend"]
    sweep["marginal_per_dollar"] = sweep["reduction"].diff() / sweep["budget"].diff()
    sweep.to_csv(ROOT / "outputs" / "budget_sweep.csv", index=False)
    nb_best = sweep.loc[sweep["net_benefit"].idxmax()]
    nb_sol = solve_scipy(build_model(inst, "max_net_benefit"))
    nb = summarize(inst, nb_sol)
    _, all_reduction, all_cost = feasible_subsets(inst)
    assert abs((all_reduction - all_cost).max() - nb["net_benefit"]) < 1.0, \
        "max_net_benefit and exhaustive search disagree"

    fig, ax = plt.subplots(figsize=(9, 5))
    # The frontier also gets the net-benefit optimum, which falls between grid points
    ok = pd.concat([sweep.dropna(subset=["reduction"])[["budget", "reduction"]],
                    pd.DataFrame({"budget": [nb["spend"]], "reduction": [nb["reduction"]]})])
    ok = ok.sort_values("budget").drop_duplicates("budget")
    ax.step(ok["budget"] / 1e3, ok["reduction"] / 1e3, where="post", color="#2b6cb0", lw=2,
            label="Max risk reduction (optimal portfolio)")
    ax.plot(ok["budget"] / 1e3, ok["budget"] / 1e3, color="grey", ls="--", lw=1,
            label="Break-even (reduction = spend)")
    ax.axhline(inst.total_ale / 1e3, color="#c53030", ls=":", lw=1)
    ax.text(ok["budget"].min() / 1e3, inst.total_ale / 1e3 * 1.015, f"Total ALE {usd(inst.total_ale)}",
            color="#c53030", fontsize=9)
    ax.scatter([budget / 1e3], [rec["reduction"] / 1e3], color="#2b6cb0", zorder=5, s=50)
    ax.annotate(f"Policy budget\n{usd(budget)}", (budget / 1e3, rec["reduction"] / 1e3),
                xytext=(15, -35), textcoords="offset points", fontsize=9)
    ax.scatter([nb["spend"] / 1e3], [nb["reduction"] / 1e3], color="#2f855a", zorder=5, s=50)
    ax.annotate(f"Max net benefit\n{usd(nb['spend'])}", (nb["spend"] / 1e3, nb["reduction"] / 1e3),
                xytext=(12, -38), textcoords="offset points", fontsize=9, color="#2f855a")
    ax.set_xlabel("Annual security budget ($k)")
    ax.set_ylabel("Annual loss expectancy removed ($k)")
    ax.set_title("Efficient frontier: how much risk each budget can buy")
    ax.legend(loc="lower right", frameon=False)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(FIG / "efficient_frontier.png", dpi=120)
    plt.close(fig)

    order = [c for c in ctl.index if any(c in v for v in selection.values())]
    grid = np.array([[c in selection.get(b, []) for b in budgets] for c in order], dtype=float)
    fig, ax = plt.subplots(figsize=(10, 0.35 * len(order) + 1.5))
    ax.imshow(grid, aspect="auto", cmap="Blues", vmin=0, vmax=1.3, interpolation="nearest")
    ax.set_yticks(range(len(order)), [ctl.at[c, "name"] for c in order], fontsize=8)
    step = 4
    ax.set_xticks(range(0, len(budgets), step), [f"{b / 1e3:.0f}" for b in budgets[::step]], fontsize=8)
    ax.set_xlabel("Budget ($k)")
    ax.set_title("Which controls the optimal portfolio funds at each budget")
    ax.text(1.0, -0.12, "Portfolios are not nested: a larger budget can swap a control out.",
            transform=ax.transAxes, ha="right", fontsize=8, color="grey")
    for s in ax.spines.values():
        s.set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG / "portfolio_by_budget.png", dpi=120)
    plt.close(fig)

    key = sweep[sweep["budget"].isin([300_000, 400_000, 500_000, 600_000, 700_000, 800_000,
                                      1_000_000, 1_200_000])].copy()
    key_fmt = pd.DataFrame({
        "budget": key["budget"].map(usd), "spend": key["spend"].map(usd),
        "risk_reduction": key["reduction"].map(usd),
        "share_of_ALE": (key["reduction"] / inst.total_ale).map("{:.0%}".format),
        "net_benefit": key["net_benefit"].map(usd),
        "controls": key["n_controls"].astype(int), "MSSP": key["mssp"].map({True: "yes", False: "no"})})
    out.append("## 3. Budget sweep\n\n"
               f"The cheapest portfolio that satisfies every policy rule costs "
               f"**{usd(min_spend.objective)}**; below that the problem is infeasible.\n\n"
               + md_table(key_fmt) + "\n\n"
               f"Net benefit (risk removed minus spend) peaks at **{usd(nb['spend'])}** of spend "
               f"({usd(nb['net_benefit'])}), found directly by the `max_net_benefit` objective and "
               f"confirmed by exhaustive search (the sweep's best grid point is "
               f"{usd(nb_best['budget'])}). Beyond that, each extra "
               "dollar buys less than a dollar of risk reduction. Spending more can still be right "
               "if leadership's risk appetite demands a lower residual ALE, but it's a risk "
               "decision, not an ROI one.\n\n"
               "![Efficient frontier](figures/efficient_frontier.png)\n\n"
               "![Portfolio by budget](figures/portfolio_by_budget.png)\n")

    # ---- 4. Greedy baseline -----------------------------------------------------------------
    greedy = []
    for b in [300_000, 400_000, 500_000, 600_000, 700_000, 800_000, 900_000, 1_000_000]:
        g = greedy_portfolio(inst, float(b))
        m = summarize(inst, optimal_portfolio(inst, float(b)))
        greedy.append({"budget": usd(b), "greedy_spend": usd(g["spend"]),
                       "greedy_reduction": usd(g["reduction"]),
                       "optimal_reduction": usd(m["reduction"]),
                       "optimal_minus_greedy": usd(m["reduction"] - g["reduction"]),
                       "rules_greedy_breaks": ", ".join(g["broken"]) or "none"})
    out.append("## 4. Baseline: buying controls by bang for the buck\n\n"
               "Greedy rule: start from the mandated controls, then keep adding the control with the "
               "most risk reduction per extra dollar (platform and MSSP fees included) that still fits "
               "the budget, product conflicts, prerequisites and analyst hours. It has no way to plan "
               "for the coverage or ratio rules, so the table reports the rules it breaks.\n\n"
               + md_table(pd.DataFrame(greedy)) + "\n\n"
               "Where greedy beats the optimizer, it does so by skipping a required CSF function. "
               "Where it follows the rules, it can still leave risk reduction on the table, because "
               "the best portfolio at a larger budget isn't the smaller one plus extras.\n")

    # ---- 5. Robustness to uncertain control effects ----------------------------------------
    unc = effect_uncertainty(inst, budget, draws=draws)
    regret = unc["regret"]
    freq = unc["frequency"][unc["frequency"] > 0].sort_values(kind="stable")
    no_regret = [c for c in unc["nominal"] if unc["frequency"][c] == 1.0]
    fig, ax = plt.subplots(figsize=(9, 0.3 * len(freq) + 1.6))
    colors = ["#2b6cb0" if c in unc["nominal"] else "#a0aec0" for c in freq.index]
    ax.barh([ctl.at[c, "name"] for c in freq.index], 100 * freq, color=colors)
    ax.set_xlim(0, 100)
    ax.set_xlabel(f"Share of {unc['draws']} effect draws in which the optimal portfolio funds it (%)")
    ax.set_title(f"Which controls hold up when effects are uncertain ({usd(budget)} budget)")
    ax.tick_params(axis="y", labelsize=8)
    ax.legend(handles=[Patch(color="#2b6cb0", label="In the recommended portfolio"),
                       Patch(color="#a0aec0", label="Not recommended")],
              loc="lower right", frameon=False, fontsize=8)
    ax.grid(axis="x", alpha=0.3)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG / "effect_uncertainty.png", dpi=120)
    plt.close(fig)
    freq_tbl = pd.DataFrame({
        "control": [ctl.at[c, "name"] for c in freq.index[::-1]],
        "recommended": ["yes" if c in unc["nominal"] else "" for c in freq.index[::-1]],
        f"draws_chosen (of {unc['draws']})":
            (freq.to_numpy()[::-1] * unc["draws"]).round().astype(int)})
    out.append("## 5. Robustness to uncertain control effects\n\n"
               "Each effect is drawn from its triangular range in `control_effects.csv` "
               f"(`reduction_min`, `reduction`, `reduction_max`), {unc['draws']} times (seed 2026), "
               f"and the {usd(budget)} portfolio is re-optimized for every draw. **Regret** is the "
               "risk reduction the recommended portfolio gives up against that draw's best one.\n\n"
               f"- The recommended portfolio is exactly optimal in "
               f"**{unc['share_nominal_optimal']:.0%}** of draws.\n"
               f"- Regret: mean **{usd(regret.mean())}**, 95th percentile "
               f"{usd(np.percentile(regret, 95))}, worst {usd(regret.max())}, against "
               f"{usd(rec['reduction'])} of risk removed at the nominal effects.\n"
               f"- Chosen in every draw: "
               f"{', '.join(ctl.at[c, 'name'] for c in no_regret)}.\n\n"
               + md_table(freq_tbl) + "\n\n"
               "![Effect uncertainty](figures/effect_uncertainty.png)\n")

    # ---- 6. Sensitivity: slack, marginal value, price of each policy rule ---------------
    hours_used = rec["analyst_hours"]
    slack = pd.DataFrame([
        {"constraint": "Budget", "limit": usd(budget), "used": usd(rec["spend"]),
         "slack": usd(budget - rec["spend"])},
        {"constraint": "Analyst hours", "limit": f"{capacity:,}", "used": f"{hours_used:,.0f}",
         "slack": f"{capacity - hours_used:,.0f}"},
        *[{"constraint": f"Coverage: {fn}", "limit": f">= {inst.policy['min_per_function']}",
           "used": int(ctl.loc[rec["controls"], "csf_function"].eq(fn).sum()),
           "slack": int(ctl.loc[rec["controls"], "csf_function"].eq(fn).sum())
           - inst.policy["min_per_function"]} for fn in CSF_FUNCTIONS],
    ])
    lp = lp_relaxation(model)
    row = sweep.loc[sweep["budget"] == budget]
    marginal = float(row["marginal_per_dollar"].iloc[0]) if len(row) else float("nan")

    rules = {
        "Mandatory phishing-resistant MFA": {"mandatory": []},
        "At least one control per CSF function": {"min_per_function": 0},
        "Protect <= 2 x (Detect + Respond + Recover)": {"max_protect_ratio": None},
        "MSSP option available": {"mssp": None},
    }
    price_budgets = sorted({300_000, 400_000, int(budget), 1_000_000})
    base = {b: optimal_portfolio(inst, float(b)) for b in price_budgets}
    price = []
    for rule, override in rules.items():
        alt_inst = load(**override)
        row = {"policy rule": rule}
        for b in price_budgets:
            alt = optimal_portfolio(alt_inst, float(b))
            if not (alt.optimal and base[b].optimal):
                row[f"at {usd(b)}"] = "n/a"
                continue
            delta = summarize(alt_inst, alt)["reduction"] - summarize(inst, base[b])["reduction"]
            row[f"at {usd(b)}"] = usd(delta)
        price.append(row)
    out.append("## 6. Sensitivity\n\n**Constraint slack at the recommended portfolio:**\n\n"
               + md_table(slack) + "\n\n"
               f"**Marginal value of budget.** Going from {usd(budget - 25_000)} to {usd(budget)} "
               f"bought {marginal:.2f} dollars of risk reduction per extra dollar (from the sweep). "
               f"The LP relaxation's shadow price on the budget is "
               f"{lp.duals.get('budget', 0):.2f}; for a 0/1 problem that dual is only indicative, "
               "which is why the sweep is the number to quote.\n\n"
               "**Price of each policy rule:** extra risk reduction gained by re-optimizing with the "
               "rule removed. For the MSSP row the option is taken away, so a negative number is "
               "what having the option is worth.\n\n" + md_table(pd.DataFrame(price)) + "\n\n"
               "$0 means relaxing the rule buys nothing at that budget. A rule can be tight (zero "
               "slack) and still cost nothing, when another portfolio of equal value exists.\n")

    # ---- 7. Minimum cost to hit a risk target ---------------------------------------
    targets = []
    for share in (0.4, 0.5, 0.6, 0.7):
        s = solve_scipy(build_model(inst, "min_cost", target_share=share))
        if s.optimal:
            r = summarize(inst, s)
            reach = all_reduction >= share * inst.total_ale - 1e-6
            assert abs(all_cost[reach].min() - r["spend"]) < 1.0, \
                "min_cost and exhaustive search disagree"
            targets.append({"target": f"{share:.0%} of ALE", "min_spend": usd(r["spend"]),
                            "achieved": f"{r['reduction'] / inst.total_ale:.1%}",
                            "controls": len(r["controls"])})
        else:
            targets.append({"target": f"{share:.0%} of ALE", "min_spend": "infeasible",
                            "achieved": "", "controls": ""})
    out.append("## 7. Minimum spend to reach a risk-reduction target\n\n"
               + md_table(pd.DataFrame(targets))
               + "\n\nExhaustive search finds the same minimum spend for every target.\n")

    n_int = sum(model.integer)
    out.append(f"## 8. Model size\n\n{len(model.names)} variables ({n_int} binary), "
               f"{len(model.constraints)} constraints. LP relaxation bound "
               f"{usd(lp.objective)} vs. integer optimum {usd(rec['reduction'])} "
               f"(gap {(lp.objective - rec['reduction']) / rec['reduction']:.1%}).\n")

    (ROOT / "docs" / "results.md").write_text("\n".join(out), encoding="utf-8")
    # Timings go to the console only, so docs/results.md is identical on every run
    print(f"MILP solve {solve_ms:.0f} ms, exhaustive search {bf_s:.1f} s")
    print(f"Recommended at {usd(budget)}: {rec['controls']}")
    print(f"  spend {usd(rec['spend'])}, reduction {usd(rec['reduction'])}, ROSI {rec['rosi']:+.0%}")
    print("Results written to docs/results.md")
    return rec


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--budget", type=float, default=None, help="annual budget in dollars")
